import assert from "node:assert/strict";
import { test } from "node:test";
import { analyze } from "../src/pipeline.js";

const positives = [
  ["이어진 압박 요약","형 명의로 온 쪽지에 현금 요구가 접수됐습니다. 당장이라면서 이 요구를 반복했다고 기록했습니다.","R13"],
  ["별개 번호로 수신한 요약","처음 보는 번호에서 누나 이름으로 도착한 연락에 금전 요구가 접수됐습니다.","R3"],
  ["같은 요구에 붙은 재촉","사촌 명의로 받은 메시지에 송금 요구와 재촉이 함께 담겼습니다.","R13"],
];
for (const [label, text, rule] of positives) {
  test(label + "에 기존 위험 규칙이 적용된다", async () => {
    const result = await analyze({ text, ai: null });
    assert.equal(result.level, "위험");
    assert.ok(result.fired_rules.includes(rule));
    assert.ok(result.signals_code.includes("SIG_FAMILY_IMPERSONATION"));
    assert.ok(result.signals_code.includes("SIG_MONEY"));
  });
}

