import { describe, it } from "node:test";
import assert from "node:assert/strict";
import { analyze } from "../src/pipeline.js";
import { SIG_DELETE_APP } from "../src/signals.js";

describe("현행 보안 앱 제거 요구를 옮긴 수신 보고", () => {
  const deletionDemands = [
    ["보호 프로그램 제거가 상담 절차로 요구됨", "상담 기록에 따르면 상대방이 제 휴대전화에 설치된 보안 프로그램을 먼저 제거하는 절차를 요구했습니다. 저는 따르지 않았습니다."],
    ["기존 백신 제거를 선행 단계로 지정", "수신 기록에는 상대가 개인 단말에 설치된 백신 앱의 제거를 선행 절차로 지정했다고 적혀 있습니다."],
    ["금융 앱 제거와 그 연락이 지정한 접수 경로", "수신 보고에 따르면 금융회사 안전 담당을 자처한 발신인이 제가 쓰는 모바일 뱅킹 앱을 지운 뒤 본인이 지정한 번호로만 회신하라고 했습니다."],
    ["통신 앱 제거와 발신자가 정한 연락처", "상담 기록에 따르면 통신사 담당자를 자처한 상대가 수신자의 통신사 앱을 제거하도록 요구했고, 이어서 상대가 지정한 번호로 연락하라고 적었습니다."],
  ];

  for (const [name, text] of deletionDemands) {
    it(name, async () => {
      const result = await analyze({ text });
      assert.ok(result.signals_code.includes(SIG_DELETE_APP));
      assert.ok(result.fired_rules.includes("R9"));
      assert.equal(result.level, "위험");
    });
  }

  const ordinaryNotices = [
    ["회사 기기 교체", "전산실 공지에서 회사 지급 단말의 보안 프로그램을 제거하는 절차를 요구했다고 회의록에 적었습니다. 새 프로그램은 정기 교체 때 전산실이 설치합니다."],
    ["기기 반납 정비", "대여 단말 반납 점검에 따라 공용 기기 보호 앱 제거 절차가 있다고 정비 안내를 받았습니다."],
    ["정상 교체를 위한 사용자 문의", "제가 먼저 보호 프로그램 제거 절차를 요청했다는 서비스 기록을 받았습니다. 공식 관리 창구에서 정상 교체 여부를 문의했습니다."],
    ["요청 사실 부인", "제 휴대전화의 보안 앱을 제거하는 절차를 요청한 사실은 없다는 답변을 받았습니다."],
    ["약관의 절차 안내", "이용 약관에는 보안 앱을 제거하는 절차가 소개되어 있다고 적혀 있습니다. 개인 휴대전화에서 실행하라는 요구는 없었습니다."],
    ["끝난 정비 작업", "정비 이력에는 지난번 보안 앱 제거 작업이 이미 완료됐다고 적혀 있으며 이번에 새로 요청받은 작업은 없습니다."],
    ["수신자 아닌 운영자에게 한 요구", "상담 메모에 따르면 장비 관리 직원에게 보안 프로그램을 먼저 제거하는 절차를 요구했습니다. 저는 관리자에게 온 내용을 읽었습니다."],
    ["발신자의 제거 요구 철회", "상대가 제 휴대전화의 보호 도구를 먼저 제거하는 절차를 요구했다는 기록입니다. 발신자가 그 요구를 취소했습니다."],
    ["악성 앱을 제거하는 보안 안내", "보안 공지에는 기기를 검사한 뒤 가짜 보안 앱을 제거하는 절차를 따르라고 기록돼 있습니다."],
    ["삭제 여부를 확인하는 도움말", "답변에는 설치된 보안 앱을 삭제하는 절차가 필요한지 전산 창구에서 확인해 달라는 요청만 담겼습니다."],
    ["은행이 알린 자체 이용 종료", "은행에서 오래된 모바일 뱅킹 앱을 이미 종료했다는 안내문을 받았습니다. 별도의 전화나 제거 요청은 없었습니다."],
    ["통상적인 앱 교체", "은행 담당자의 점검 기록에는 제가 쓰는 모바일 뱅킹 앱을 지운 뒤 같은 공식 앱을 다시 설치하는 방법만 설명돼 있습니다."],
    ["별개의 발신자가 제시한 연락처", "은행 안전 담당을 자처한 연락에서는 제가 쓰는 모바일 뱅킹 앱을 지운 뒤 다시 설치하는 방법만 설명했습니다. 그와 별개로 다른 사람이 자신이 지정한 번호로 회신하라고 했습니다."],
    ["제거 금지 공지", "금융회사에서 주의 안내를 받았습니다. 누가 따로 연락해도 수신자가 쓰는 뱅킹 앱을 지우거나 다른 번호로 전화하지 말라고 알렸습니다."],
  ];

  for (const [name, text] of ordinaryNotices) {
    it(name, async () => {
      const result = await analyze({ text });
      assert.ok(!result.signals_code.includes(SIG_DELETE_APP));
      assert.ok(!result.fired_rules.includes("R9"));
    });
  }
});
