import assert from "node:assert/strict";
import { test } from "node:test";
import { analyze } from "../src/pipeline.js";

const positives = [
  ["통화를 거절하고 글로만 답하겠다는 동일 발신자의 수신 보고","보낸 사람은 누나라고 소개했습니다. 제가 통화하자고 했더니 통화는 못 한다고 답했고 메시지로만 이야기하겠다고 기록했습니다.","R4","SIG_AVOID_VOICE"],
  ["금전 목적물의 일부를 다른 연락처에서 요구한 수신 보고","작은아들이라고 온 메시지였습니다. 발신 연락처를 바꿨다고 했고 회비 일부를 대신 부담해 달라는 요구가 기록됐습니다.","R3","SIG_MONEY"],
  ["금전 목적물의 나머지를 새 연락처에서 요구한 수신 보고","동생이라고 온 쪽지였습니다. 연락처가 바뀌었습니다. 부담금의 나머지를 마련해 달라는 요구가 있었습니다.","R3","SIG_MONEY"],
];
for (const [label, text, rule, signal] of positives) {
  test(label, async () => {
    const result = await analyze({ text, ai: null });
    assert.equal(result.level, "위험");
    assert.ok(result.fired_rules.includes(rule));
    assert.ok(result.signals_code.includes("SIG_FAMILY_IMPERSONATION"));
    assert.ok(result.signals_code.includes(signal));
  });
}

