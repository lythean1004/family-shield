import { describe, it } from "node:test";
import assert from "node:assert/strict";
import { analyze } from "../src/pipeline.js";
import { cashEventSignals } from "../src/institution-report-frames.js";

describe("현금 행위와 수취인 관계", () => {
  const current = [
    ["현금 인계 지시 뒤 같은 인계의 방문 수취인", "R15",
      "수사기관 담당자라고 밝힌 발신자가 보낸 연락을 받았습니다. 현찰을 인계하라는 요구가 들어 있었고, 그 인계의 수취인은 방문하는 직원이라고 적혔습니다."],
    ["방문하는 수취인을 먼저 명시", "R15",
      "검찰청 담당자라고 소개한 발신자가 보낸 연락을 받았습니다. 방문할 담당자에게 제 현금을 넘기라는 지시가 있었다고 기록했습니다."],
    ["먼저 알려 준 직원 방문과 같은 대출금 현장 수취", "R18",
      "금융회사 대출 담당자라고 밝힌 발신자가 보낸 연락을 받았습니다. 담당 직원이 방문할 예정이며 대출 상환금을 현찰로 현장에서 수거하겠다고 설명했습니다."],
    ["같은 절의 대출 직원이 자기 방문을 명시", "R18",
      "은행 대출 담당자라고 밝힌 발신자가 대출 상환금을 현찰로 준비하면 자신이 방문해 받아 가겠다고 설명했습니다."],
    ["상환 수단·발신·방문 계획의 서식 순서가 바뀜", "R18",
      "받은 대출 안내의 항목을 정리\n수거 방식 | 은행 직원이 찾아와 받아 감\n발신처 | 은행 대출 직원\n상환 수단 | 현금"],
    ["기관·수취인·현금 항목이 하나의 수신 기록", "R15",
      "받은 통지서의 항목을 기록\n받으러 오는 쪽 | 방문 담당자\n발신처 | 수사기관\n항목명 | 현찰 인계\n내가 직접 건네는 방식으로 적혀 있음."],
    ["상환금 인수 계획과 방문 담당의 명시", "R18",
      "은행 대출 담당자라고 소개한 발신자가 보낸 연락을 받았습니다. 대출 상환액은 현금으로 받겠다고 했으며, 그 수거의 담당자는 집을 방문하는 직원이라고 적었습니다."],
  ];
  for (const [name, rule, text] of current) {
    it(name, async () => {
      assert.equal([...cashEventSignals(text)].length, 1);
      assert.ok((await analyze({text})).fired_rules.includes(rule));
    });
  }

  const ordinary = [
    ["기관의 안내는 대면 환급", "수사기관 담당자라고 밝힌 발신자가 연락했습니다. 방문하는 직원이 수신자에게 환급액을 현금으로 반환하겠다는 통지였습니다."],
    ["다른 발신자의 방문", "은행 대출 담당자라고 밝힌 발신자의 연락을 받았습니다. 상환 금액과 납부일만 적혀 있습니다. 그와 별개로 다른 직원이 현찰로 받아 가겠다며 방문 이야기를 했습니다."],
    ["현금과 수거할 서류는 다른 목적어", "은행 대출 담당자라고 소개한 발신자의 연락을 받았습니다. 현금 상환 방법을 안내했고 방문하는 담당자는 영수증을 수거하겠다고 말했습니다."],
    ["영업점에서 고객이 내는 돈", "금융회사 대출 담당자라고 밝힌 발신자의 안내를 받았습니다. 고객이 영업점에 방문하면 담당 직원이 현금 상환을 접수할 수 있다는 안내였습니다."],
    ["수신자와 직원 사이에서 반대 방향", "수사기관 담당자라고 밝힌 발신자의 연락을 받았습니다. 방문할 직원이 제게 보관한 현찰을 건네 준다고 했고 제가 현금을 낼 일은 없었습니다."],
    ["방문은 최근이지만 현금은 이미 처리", "은행 대출 담당자라고 밝힌 발신자의 연락을 받았습니다. 대출 상환금은 현찰로 납부가 끝났고 직원은 다음 주 방문으로 일정을 잡았다고 합니다."],
    ["방문과 수취를 다른 인물에게 배정", "금융회사 대출 담당자라고 소개한 발신자의 연락을 받았습니다. 담당 직원은 방문하고 현찰 상환금은 지점의 다른 창구 직원이 수령하겠다고 알려 왔습니다."],
    ["이미 철회된 수거 요구", "은행 대출 담당자라고 소개한 발신자의 문자를 받았습니다. 직원이 방문해서 대출 상환금을 현금으로 수거할 예정이라는 안내였습니다. 해당 수거 계획은 철회됐습니다."],
    ["수사기관 발신자 소개가 없는 매장 결제", "받은 매장 안내를 옮겼습니다. 배송 직원이 방문할 때 현찰로 물건 값을 계산할 수 있다는 일반 안내였습니다."],
    ["가정형 문의와 다른 문장의 인계", "수사기관 담당자라고 밝힌 발신자의 연락을 받았습니다. 현찰을 방문 직원에게 넘겨야 하는지 제가 문의했고 발신자는 아직 정해진 것이 없다고 답했습니다."],
  ];
  for (const [name, text] of ordinary) {
    it(name, async () => {
      assert.deepEqual([...cashEventSignals(text)], []);
      if (name === "수신자와 직원 사이에서 반대 방향") return;
      const result = await analyze({text});
      assert.ok(!result.fired_rules.includes("R15"));
      assert.ok(!result.fired_rules.includes("R18"));
    });
  }
});
