import { describe, it } from "node:test";
import assert from "node:assert/strict";
import { analyze } from "../src/pipeline.js";

describe("수사기관을 대표한다고 한 발신자의 현금 수취인", () => {
  const cases = [
    ["소속·수거인의 연결", true,
      "경찰서에서 나왔다고 밝힌 사람이 현찰을 같은 기관의 수사관에게 직접 건네라는 말을 했다는 기록이다."],
    ["직원을 보낸 주체가 명확", true,
      "검찰청에서 파견됐다고 설명한 발신자가 현금을 자신이 보낸 직원에게 직접 전달하라는 요구를 했다고 적었다."],
    ["기관 대표와 자기 쪽 수취인", true,
      "수사기관을 대표해 왔다고 한 담당자가 현찰을 자기 소속 직원에게 직접 인계하라는 지시를 했다고 기록했다."],
    ["건물 방문과 개인 거래", false,
      "경찰서에서 나왔다고 한 사람이 개인 물건을 샀다는 기록이다. 현금은 가게 직원에게 건네는 결제 수단이라고 했다."],
    ["제삼자의 소속", false,
      "수사기관에서 나왔다는 이웃의 이야기를 들었다. 받은 연락의 상대는 현금을 자기 소속 직원에게 건네겠다고 했다."],
    ["받는 물건은 서류", false,
      "검찰청에서 파견됐다고 밝힌 발신자가 현금 보관 상태를 물었고 자기 소속 직원에게 확인 서류를 전달하라는 말을 했다는 기록이다."],
    ["수신자가 직원에게 받음", false,
      "경찰서에서 나왔다고 한 담당자가 같은 기관의 직원에게 현찰을 받아 수신자인 저에게 건네겠다는 절차를 설명했다고 했다."],
    ["강의 속 인용", false,
      "예방 교육 자료에서 수사기관을 대표해 왔다고 한 담당자가 현금을 자기 소속 직원에게 직접 건네라는 장면을 다뤘다."],
    ["인계 요구 취소", false,
      "검찰청에서 파견됐다고 밝힌 발신자가 현찰을 자신이 보낸 직원에게 직접 전달하라는 요구를 했다고 적었다. 해당 요청은 취소됐다."],
    ["현금 수취인과 서류 수취인이 다른 기록", false,
      "경찰서에서 나왔다고 한 사람이 현찰을 옆 가게에 직접 전달하라는 말을 했고 자기 쪽 직원에게 일정표를 주었다고 기록했다."],
    ["수거인을 현금 앞에 기록", true,
      "검찰청에서 파견됐다고 밝힌 상대가 자신이 보낸 담당자에게 현찰을 직접 인계하라는 요구를 했다고 기록했다."],
  ];
  for (const [name, expected, text] of cases) {
    it(name, async () => {
      const result = await analyze({ text });
      assert.equal(result.fired_rules.includes("R15"), expected);
    });
  }
});
