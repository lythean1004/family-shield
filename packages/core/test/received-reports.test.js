test("평판·도메인 나이 서술은 실제 검사에 사용되지 않는다", async () => {
  let queries = 0;
  const lookup = async () => { queries++; return { ok: true, malicious: [], young: [] }; };
  const result = await analyze({
    text: "도메인이 막 등록됐거나 차단 목록에 있다고 메모했다. 실제 주소와 조회 결과는 기록하지 않았다.",
    urlReputation: lookup,
    domainAge: lookup,
  });
  assert.equal(queries, 0);
  assert.equal(result.level, "확인필요");
});

test("금융 비밀 입력 요구의 주소 근거는 해당 양식에만 연결한다", async () => {
  const report = "받은 알림을 분류했습니다. 상대가 보낸 확인 양식에 금융 비밀값 입력을 요구했다는 내용입니다.";
  for (const extra of ["", " 다음 행사 안내: https://event.invalid/news", " 해당 양식 주소: https://www.gov.kr/ · 외부 참고 https://extra.invalid/ref"]) {
    assert.ok(!(await analyze({ text: report + extra })).fired_rules.includes("R16"));
  }
});

