import { describe, it } from "node:test";
import assert from "node:assert/strict";
import { analyze } from "../src/pipeline.js";
import { SIG_APP_INSTALL, SIG_CALL_THIS_NUMBER, SIG_CASH_HANDOVER, SIG_LINK, SIG_LOAN_CASH_PICKUP } from "../src/signals.js";

describe("수신 보고의 기관 역할과 의무·방문·목적지", () => {
  const positives = [
    ["현행 창구를 대체하는 문자의 주소", "R6", SIG_LINK,
      "발신자는 군청 민원 담당이라고 말했습니다. 군청이 운영하는 접수처와 다른 help-queue.invalid로 접속할 것을 요구한 상담 기록입니다."],
    ["수신 통지에 적힌 유일한 번호를 가리키는 답장", "R6", SIG_CALL_THIS_NUMBER,
      "공공기관 민원 담당이라고 설명한 통지였습니다. 그 통지에 000-0000-1234가 기재되어 있었으며, 이 연락처로 통화해야 안내를 받을 수 있다고 적었습니다."],
    ["기관을 자칭한 사람이 안내 처리 조건으로 기기 설치 요구", "R6", SIG_APP_INSTALL,
      "시청 쪽이라고 한 상대가 접수 절차를 진행하려면 수신자의 기기에 별도 프로그램을 설치해야 한다고 요구했다고 적었습니다."],
    ["수사기관 발신 주장과 수신자의 현찰 전달", "R15", SIG_CASH_HANDOVER,
      "자신이 경찰서에서 직접 연락하는 중이라고 밝힌 발신자가 직접 만나 현찰을 전달하라고 요구한 사실을 상담 기록에 남겼습니다."],
    ["대출 담당 부서 명의와 직원의 방문 수취", "R18", SIG_LOAN_CASH_PICKUP,
      "은행 대출 담당자라는 메시지였습니다. 상환금을 현찰로 준비하면 직원이 방문해 받아 간다는 설명이 담겼습니다."],
  ];
  for (const [name, rule, cue, text] of positives) {
    it(name, async () => {
      const result = await analyze({ text });
      assert.ok(result.signals_code.includes(cue));
      assert.ok(result.fired_rules.includes(rule));
    });
  }

  const negatives = [
    ["기관을 내세우지 않은 설비 담당자의 안내", "설비 점검 담당자라는 사람이 기존 창구 대신 service-queue.invalid로 접속하라고 요구했다고 기록했습니다."],
    ["조사가 붙은 공식 호스트의 안내", "발신자는 군청 담당자라고 말했습니다. 평소 접수처 대신 www.gov.kr로 접속하라고 안내했습니다."],
    ["현재 사건의 연락처가 둘", "공공기관 민원 담당이라는 문자였습니다. 그 문자에 000-0000-1234와 000-0000-5432가 기재됐고, 그 번호로 전화해야 한다고 했습니다."],
    ["번호 칸이 비어 있음", "공공기관 민원 담당이라는 통지였습니다. 그 안에 번호가 생략됐고 그 연락처는 전화해야 접수된다고 했습니다."],
    ["전화가 필요한지 문의", "은행 담당이라고 설명한 메시지였습니다. 그 메시지에 000-0000-1234가 표시돼 있었는데, 그 번호로 전화해야 하는지를 제가 문의했습니다."],
    ["직원 기기 설치", "시청 쪽이라고 한 상대가 접수 전에 직원용 기기에 별도 프로그램을 설치해야 한다고 설명했습니다."],
    ["수신자의 돈을 받아 주는 쪽과 별개인 사람", "경찰서에서 연락했다는 사람이 전달한 설명은 담당자가 직원을 만나 현금을 건네야 한다는 말이었다고 기록했습니다."],
    ["현재의 수거가 아니라 이미 종료", "은행 대출 담당이라는 연락입니다. 지난번 상환금은 직원이 방문해 수거했고 현재 절차는 끝났다고 알렸습니다."],
    ["별개 발신자가 현금 방문 수취", "은행 대출 담당이라는 메시지였습니다. 그와 별개로 다른 사람이 상환금을 준비하면 집에 와서 현금으로 수거한다고 했습니다."],
    ["기관의 연락을 받았다는 시민", "경찰서에서 연락했다는 사람이 상담 기록에 등장합니다. 그 사람은 직접 만나 현찰을 넘기라고 했지만 기관 소속이라고 자신을 밝힌 적은 없습니다."],
    ["기관이 연락했다는 독립 경험", "수사기관이 연락했다는 사람이 직접 만나 현금을 넘기라는 말을 했다는 수신 기록입니다."],
    ["발신자가 제삼자를 담당자로 소개함", "지역 주민을 공공기관 민원 담당이라고 소개한 문자였습니다. 그 안에 000-0000-1234가 기재되어 있었고 그 번호로 전화해야 한다는 설명입니다."],
    ["누군가를 조사 담당자로 소개한 뒤 인계를 언급", "받은 기록에는 이웃을 경찰서 조사 담당자라고 소개한 발신자가 직접 만나 현금을 전달하라고 요구한 대목이 있었습니다."],
    ["발신 역할 표기가 실제 연락이 아니라 형식 예시", "작성 형식 예시에는 자신이 경찰서에서 직접 연락하는 중이라고 밝힌 발신자의 말이 들어 있습니다. 직접 만나 현찰을 전달하라고 요구한 대목은 예시 문장입니다."],
    ["접수에 필요한 단순 본인 확인", "시청 쪽이라고 한 상대가 받은 안내의 날짜와 이름이 맞는지만 기존 기기에서 직접 확인하라고 설명했습니다."],
  ];
  for (const [name, text] of negatives) {
    it(name, async () => {
      const result = await analyze({ text });
      assert.ok(!result.fired_rules.includes("R6"));
      assert.ok(!result.fired_rules.includes("R15"));
      assert.ok(!result.fired_rules.includes("R18"));
    });
  }
});
